#!/usr/bin/env python3
"""Build report/tables.md from the CSV files in report/data/.

Usage: python3 report/make_tables.py
"""
import collections
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "data")

SOURCES = {
    "input001": ("ibm01-cu85", "mild"), "input002": ("ibm01-cu88", "mild"),
    "input003": ("ibm10-cu90", "mild"), "input004": ("ibm10-cu95", "mild"),
    "input005": ("ibm12-cu85", "mild"), "input006": ("ibm12-cu90", "mild"),
    "input007": ("ibm01-cu85", "harsh"), "input008": ("ibm01-cu88", "harsh"),
    "input009": ("ibm10-cu90", "harsh"), "input010": ("ibm10-cu95", "harsh"),
    "input011": ("ibm12-cu85", "harsh"), "input012": ("ibm12-cu90", "harsh"),
}


def load(name):
    with open(os.path.join(DATA, name)) as f:
        return list(csv.DictReader(f))


def m(x):
    """Millions with 2 decimals."""
    return "%.2fM" % (float(x) / 1e6)


def pct(a, b):
    return 100.0 * (float(a) / float(b) - 1.0)


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def final_results():
    rows = []
    for r in load("run_final.csv"):
        src, noise = SOURCES[r["case"]]
        rows.append([
            r["case"], "%s %s" % (src, noise), "{:,}".format(int(r["cells"])),
            "%s / %s" % (m(r["d_total"]), m(r["ref_d_total"])),
            "%.0f / %.0f" % (float(r["d_max"]), float(r["ref_d_max"])),
            m(r["hpwl_legal"]), m(r["hpwl_sa"]), "%.1f%%" % -float(r["improve_pct"]),
            "%+.1f%%" % pct(r["hpwl_sa"], r["ref_hpwl"]), m(r["ref_hpwl"]), r["seconds"], r["checker"]])
    return table(["case", "source (GP noise)", "cells", "D_total ours / Dragon", "D_max ours / Dragon",
                  "HPWL legal", "HPWL SA", "SA gain", "SA vs Dragon", "Dragon HPWL", "time (s)", "checker"], rows)


def stage1_ablation():
    by = collections.defaultdict(dict)
    for r in load("stage1_ablation.csv"):
        by[r["case"]][r["config"]] = r
    cfgs = ["abacus", "abacus+l1", "abacus+post", "full"]
    rows = []
    sums = collections.defaultdict(lambda: [0.0, 0.0])
    for c in sorted(by):
        base = by[c]["abacus"]
        row = [c]
        for k in cfgs:
            r = by[c][k]
            row.append("%s / %.0f" % (m(r["d_total"]), float(r["d_max"])))
            sums[k][0] += pct(r["d_total"], base["d_total"])
            sums[k][1] += pct(r["d_max"], base["d_max"])
        row.append(by[c]["full"]["stage1_s"])
        rows.append(row)
    n = len(by)
    rows.append(["**mean vs Abacus**"] + ["%+.1f%% / %+.1f%%" % (sums[k][0] / n, sums[k][1] / n) for k in cfgs]
                + [""])
    return table(["case", "Abacus only", "+ L1 reposition", "+ post-pass (no L1)", "full Stage 1", "Stage 1 time (s)"],
                 rows)


def sa_progression():
    base = {r["case"]: r for r in load("run_phase4_baseline.csv")}
    mid = {r["case"]: r for r in load("run_phase5_schedule.csv")}
    fin = {r["case"]: r for r in load("run_final.csv")}
    rows = []
    for c in sorted(fin):
        rows.append([c, m(base[c]["hpwl_sa"]), m(mid[c]["hpwl_sa"]), m(fin[c]["hpwl_sa"]),
                     "%+.1f%%" % pct(fin[c]["hpwl_sa"], base[c]["hpwl_sa"])])
    mean = lambda d: sum(pct(d[c]["hpwl_sa"], base[c]["hpwl_sa"]) for c in fin) / len(fin)  # noqa: E731
    rows.append(["**mean change**", "", "%+.1f%%" % mean(mid), "%+.1f%%" % mean(fin), ""])
    return table(["case", "phase 4 SA", "+ speed-up & schedule", "+ generalized swap (final)", "total"], rows)


def sweeps():
    groups = collections.OrderedDict()
    for r in load("sa_sweeps.csv"):
        groups.setdefault(r["experiment"], []).append(r)
    cases = ["input001", "input005", "input011"]
    rows = []
    for exp, rs in groups.items():
        ref = next(r for r in rs if r["note"].startswith("chosen"))
        for r in rs:
            rel = sum(pct(r[c], ref[c]) for c in cases) / len(cases)
            rows.append([exp, r["setting"], m(r["input001"]), m(r["input005"]), m(r["input011"]),
                         "—" if r is ref else "%+.2f%%" % rel, r["note"]])
    return table(["experiment", "setting", "input001", "input005", "input011", "mean vs chosen", "note"], rows)


def validity():
    rows = [[r["move"], "{:,}".format(int(r["attempts"])), "{:,}".format(int(r["valid_proposals"])),
             r["valid_pct"] + "%"] for r in load("move_validity.csv")]
    return table(["move type", "attempts", "valid proposals", "valid"], rows)


def main():
    parts = [
        "# Report tables\n\nGenerated by `report/make_tables.py` from `report/data/`. "
        "Do not edit by hand.\n",
        "## T1. Final results (12 ibm-place2-derived cases)\n\n"
        "Dragon = the unperturbed Dragon placement each GP was derived from (a known legal "
        "solution), measured against the same GP. HPWL uses cell centers, so Dragon's own "
        "pin-offset-aware optimization is not exactly the same objective.\n\n" + final_results(),
        "## T2. Stage 1 ablation (D_total / D_max; SA off)\n\n" + stage1_ablation(),
        "## T3. SA progression over phase 5 (HPWL after SA, full 12-case runs)\n\n" + sa_progression(),
        "## T4. SA parameter sweeps (input001 / input005 / input011)\n\n"
        "Three runs in parallel per row; repeated identical runs differ by about 0.4-1%, so "
        "only consistent differences larger than that are treated as real.\n\n" + sweeps(),
        "## T5. Valid proposals per move type (input005, 12 s SA, one move type at a time)\n\n"
        + validity(),
    ]
    out = os.path.join(HERE, "tables.md")
    with open(out, "w") as f:
        f.write("\n".join(parts))
    print("wrote", out)


if __name__ == "__main__":
    main()
